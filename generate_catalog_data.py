def generate_catalog_js():
    all_templates = []
    
    for cat in CATEGORIES:
        cat_id = cat["id"]
        cat_name = cat["name"]
        cat_icon = cat["icon"]
        titles = cat["titles"]
        
        # Ensure exactly 100 templates
        while len(titles) < 100:
            titles.append(f"{cat_name} Distinction Certificate #{len(titles) + 1}")
        titles = titles[:100]
        
        for idx, title in enumerate(titles, start=1):
            t_id = f"{cat_id}_{idx:03d}"
            theme = cat["theme_options"][(idx - 1) % len(cat["theme_options"])]
            border = cat["borders"][(idx - 1) % len(cat["borders"])]
            seal = cat["seals"][(idx - 1) % len(cat["seals"])]
            font_title, font_recip = cat["font_pairings"][(idx - 1) % len(cat["font_pairings"])]
            
            sig1_roles = {
                "event": "Event Chairperson",
                "participation": "Program Coordinator",
                "club": "Club President",
                "academic": "Dean of Academic Affairs",
                "appreciation": "Executive Director",
                "sports": "Head Coach & Director",
                "corporate": "Managing Director",
                "workshop": "Lead Technical Instructor",
                "achievement": "Grand Jury Chairperson",
                "community": "Executive Board Director"
            }
            sig2_roles = {
                "event": "Keynote Speaker",
                "participation": "Organizing Secretary",
                "club": "Faculty Advisor",
                "academic": "University Chancellor",
                "appreciation": "Chief Executive Officer",
                "sports": "Athletics Commissioner",
                "corporate": "Vice President of Talent",
                "workshop": "Program Director",
                "achievement": "President of the Academy",
                "community": "Community Relations Head"
            }
            
            all_templates.append({
                "id": t_id,
                "category": cat_id,
                "categoryName": cat_name,
                "categoryIcon": cat_icon,
                "index": idx,
                "title": title,
                "theme": theme,
                "border": border,
                "seal": seal,
                "fontTitle": font_title,
                "fontRecipient": font_recip,
                "sig1Role": sig1_roles.get(cat_id, "Authorized Signatory"),
                "sig2Role": sig2_roles.get(cat_id, "Official Director"),
                "qr": (idx % 2 == 1)
            })

    output_code = f"""/**
 * Certificate Studio Pro - Mega Certificate Template Catalog
 * 1,000 Total Real Certificate Templates across 10 Distinct Categories
 * (100 templates in each category: Event, Participation, Club, Academic, Appreciation, Sports, Corporate, Workshop, Achievement, Community)
 */

window.CERTIFICATE_CATEGORIES = {json.dumps(CATEGORIES, indent=2)};

window.MEGA_CERTIFICATE_TEMPLATES = {json.dumps(all_templates, indent=2)};

console.log('✅ Loaded Mega Certificate Catalog:', window.MEGA_CERTIFICATE_TEMPLATES.length, 'templates across 10 categories.');
"""
    with open('static/certificate_catalog.js', 'w', encoding='utf-8') as f:
        f.write(output_code)
    print(f"Successfully generated static/certificate_catalog.js with {len(all_templates)} templates!")

